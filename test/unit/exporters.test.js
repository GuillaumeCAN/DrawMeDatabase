const test = require('node:test');
const assert = require('node:assert/strict');

const exporters = require('../../views/exporters');

const SOURCE = 'erDiagram\n  users\n';
const PROJECT = { name: 'blog-app', framework: 'laravel' };

test('the Mermaid file has the title and the layout in its front matter', () => {
    assert.equal(exporters.mermaidFile(SOURCE, { project: PROJECT, layout: 'elk' }),
        '---\ntitle: "blog-app database schema"\nconfig:\n  layout: elk\n---\nerDiagram\n  users\n');
    assert.equal(exporters.mermaidFile(SOURCE, {}), '---\ntitle: "Database schema"\n---\nerDiagram\n  users\n');
    // The title is a YAML double-quoted string
    assert.ok(exporters.mermaidFile(SOURCE, { project: { name: 'a"b\\c: d' } }).includes('title: "a\\"b\\\\c: d database schema"'));
    assert.ok(!exporters.mermaidFile(SOURCE, { layout: 'other' }).includes('config'));
});

test('the Markdown file holds the diagram in a mermaid block', () => {
    const markdown = exporters.markdownFile(SOURCE, { project: PROJECT, layout: 'dagre', date: new Date('2026-10-18T10:00:00Z') });
    assert.equal(markdown, [
        '# Blog-app database schema',
        '',
        'Generated by DrawMeDatabase from the Laravel code on 2026-10-18.',
        '',
        '```mermaid',
        '---',
        'title: "blog-app database schema"',
        'config:',
        '  layout: dagre',
        '---',
        'erDiagram',
        '  users',
        '```',
        '',
    ].join('\n'));
    assert.match(exporters.markdownFile(SOURCE, {}), /^# Database schema\n\nGenerated by DrawMeDatabase from the code on \d{4}-\d{2}-\d{2}\./);
});

test('the JSON file is the indented list of tables', () => {
    assert.equal(exporters.jsonFile([{ table: 'users' }]), '[\n  {\n    "table": "users"\n  }\n]\n');
    assert.equal(exporters.jsonFile(undefined), '[]\n');
});

test('file names come from the project name, with safe characters only', () => {
    assert.equal(exporters.fileName(PROJECT, 'svg'), 'blog-app-schema.svg');
    assert.equal(exporters.fileName({ name: 'Mon projet (v2)' }, 'png'), 'Mon-projet-v2-schema.png');
    assert.equal(exporters.fileName({ name: 'café' }, 'md'), 'café-schema.md');
    assert.equal(exporters.fileName({ name: '../../etc' }, 'mmd'), 'etc-schema.mmd');
    assert.equal(exporters.fileName({}, 'json'), 'schema.json');
});
