// Text of the exported files (Mermaid source, Markdown, JSON) and their default names.
// Pure functions, loaded by the webview (classic script) and by the unit tests (CommonJS).
(function (root) {
    'use strict';

    const FRAMEWORKS = { laravel: 'Laravel', symfony: 'Symfony' };

    const frameworkName = (framework) => FRAMEWORKS[framework] || '';

    // "blog-app database schema"
    function schemaTitle(project) {
        const name = project && typeof project.name === 'string' ? project.name.trim() : '';
        return name ? `${name} database schema` : 'Database schema';
    }

    // A .mmd file: the diagram with its title and layout in the front matter, so other Mermaid
    // renderers (GitHub, Markdown previews, mermaid.live) draw it the same way
    function mermaidFile(source, { project, layout } = {}) {
        const lines = ['---', `title: ${JSON.stringify(schemaTitle(project))}`];
        if (layout === 'dagre' || layout === 'elk') {
            lines.push('config:', `  layout: ${layout}`);
        }
        lines.push('---');
        return `${lines.join('\n')}\n${source}`;
    }

    // A Markdown document with the diagram in a mermaid code block
    function markdownFile(source, { project, layout, date } = {}) {
        const framework = frameworkName(project && project.framework);
        const day = (date instanceof Date && !Number.isNaN(date.getTime()) ? date : new Date()).toISOString().slice(0, 10);
        const origin = framework ? `the ${framework} code` : 'the code';
        return [
            `# ${schemaTitle(project).replace(/^\w/, char => char.toUpperCase())}`,
            '',
            `Generated by DrawMeDatabase from ${origin} on ${day}.`,
            '',
            '```mermaid',
            mermaidFile(source, { project, layout }).replace(/\n$/, ''),
            '```',
            '',
        ].join('\n');
    }

    function jsonFile(tables) {
        return JSON.stringify(Array.isArray(tables) ? tables : [], null, 2) + '\n';
    }

    // "blog-app-schema.svg": the project name with only file-name-safe characters
    function fileName(project, extension) {
        const name = project && typeof project.name === 'string' ? project.name : '';
        const safe = name.normalize('NFC').replace(/[^\p{L}\p{N}._-]+/gu, '-').replace(/^[-.]+|-+$/g, '');
        return `${safe ? `${safe}-` : ''}schema.${extension}`;
    }

    const api = { schemaTitle, mermaidFile, markdownFile, jsonFile, fileName };
    if (typeof module === 'object' && module.exports) {
        module.exports = api;
    } else {
        root.DrawMeDatabaseExport = api;
    }
})(typeof window !== 'undefined' ? window : globalThis);
